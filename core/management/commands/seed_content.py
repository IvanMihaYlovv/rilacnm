# Swatches for products sold in set colours; hex codes are display approximations.
SEPARATE_COLLECTION_COLORS = (
    'Син | #1f5aa6 | хартиени отпадъци\n'
    'Зелен | #2e7d32 | отпадъци от стъкло\n'
    'Жълт | #f2c200 | пластмасови отпадъци'
)
PRODUCT_COLORS = {
    'Контейнери за разделно събиране': SEPARATE_COLLECTION_COLORS,
    'Метална кофа за разделно събиране': SEPARATE_COLLECTION_COLORS,
}


class Command(BaseCommand):
    help = 'Зарежда началното съдържание на сайта (идемпотентно).'

    def handle(self, *args, **options):
        with transaction.atomic():
            self._seed()
        if options['verbosity'] > 0:
            # Windows consoles may not encode Cyrillic, and seeding has already succeeded by now.
            self.stdout.write(self.style.SUCCESS(
                f'Done: {Category.objects.count()} categories, {Product.objects.count()} products, '
                f'{Project.objects.count()} projects, {News.objects.count()} news.'))

    def _seed(self):
        for c_order, (cat_name, cat_desc, cat_body, cat_meta, products) in enumerate(CATALOG):
            category, _ = Category.objects.update_or_create(
                name=cat_name,
                defaults={'description': cat_desc, 'body': cat_body, 'meta_description': cat_meta,
                          'order': c_order})
            for p_order, (name, highlight, short, desc, specs, standards, options) in enumerate(products):
                Product.objects.update_or_create(
                    name=name, category=category,
                    defaults={'highlight': highlight, 'short_description': short,
                              'description': desc, 'specifications': specs,
                              'standards': '\n'.join(standards), 'options': '\n'.join(options),
                              'colors': PRODUCT_COLORS.get(name, ''),
                              'order': c_order * 100 + p_order})

        for order, data in enumerate(PROJECTS):
            Project.objects.update_or_create(
                contract_number=data['contract_number'],
                defaults={**data, 'kind': Project.Kind.EU_FUNDED, 'order': order})

        for data in NEWS:
            data = dict(data)
            published = timezone.make_aware(datetime(*data.pop('published')))
            News.objects.update_or_create(title=data['title'], defaults={**data, 'published_at': published})
